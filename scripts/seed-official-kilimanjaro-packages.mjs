async function seed() {
  const pool = await connectDatabase();
  await initCmsStore({ pool });

  console.log(`Starting seed of ${OFFICIAL_KILIMANJARO_PACKAGES.length} official Kilimanjaro packages...`);
  const now = new Date().toISOString();

  for (const pkg of OFFICIAL_KILIMANJARO_PACKAGES) {
    let existing = await safarisRepository.findBySlug(pkg.slug, { includeUnpublished: true });
    if (!existing) {
      existing = await safarisRepository.create({
        draft: {
          ...pkg,
          status: SafariStatus.PUBLISHED,
        },
        actor: { userId: 'seed-official-kili' },
      });
    }

    const draft = {
      ...(existing.draft || {}),
      ...pkg,
      tour_type: 'mountain',
    };

    existing.draft = draft;
    existing.published = { ...draft };
    existing.status = SafariStatus.PUBLISHED;
    existing.updated_at = now;
    existing.published_at = existing.published_at || now;

    await safarisRepository.save(existing);
    console.log(`✓ Seeded official package: ${pkg.title} (${pkg.slug}) with ${pkg.itinerary.length} days`);
  }

  invalidateSiteBundle();
  console.log('✓ Invalidated site-bundle cache');
  await closeDatabase();
  console.log('All Kilimanjaro packages successfully seeded into PostgreSQL!');
}

seed().catch((err) => {
  console.error('Seed failed:', err);
  process.exit(1);
});
